     * `stopped` (상태 값): 객체가 유지하는 구성·진행 상태를 보관한다.
     * 값의 변경은 현재 패키지의 흐름과 후속 계산에 반영된다.
     */

    var stopped = false
    /**
     * `labels` (상태 값): 객체가 유지하는 구성·진행 상태를 보관한다.
     * 값의 변경은 현재 패키지의 흐름과 후속 계산에 반영된다.
     */

    val labels = MutableList(2) { "" }


    /**
     * `create`: 객체나 결과를 생성한다.
     * 입력값을 현재 타입의 규칙에 따라 처리하고 결과 또는 상태 변화를 남긴다.
     */

    fun create(v: Int) {
        flag = v; attached = true; zIndex = 1; sound++; dispatch++
    }

    /**
     * `load`: 상태나 데이터를 조회한다.
     * 입력값을 현재 타입의 규칙에 따라 처리하고 결과 또는 상태 변화를 남긴다.
     */

    fun load(name: String) {
        repeat(2) { labels[it] = name + if (flag and 1 != 0) " ▪ 훈련" else "" }
    }

    /**
     * `destroy`: 타입의 핵심 동작을 수행한다.
     * 입력값을 현재 타입의 규칙에 따라 처리하고 결과 또는 상태 변화를 남긴다.
     */

    fun destroy() {
        stopped = true
    }
}


/** BattleSortModel: 전투 화면에 전달할 불변 표시 상태를 보관한다. */
class BattleSortModel {
    /**
     * `attached` (상태 값): 객체가 유지하는 구성·진행 상태를 보관한다.
     * 값의 변경은 현재 패키지의 흐름과 후속 계산에 반영된다.
     */

    var attached = true
    /**
