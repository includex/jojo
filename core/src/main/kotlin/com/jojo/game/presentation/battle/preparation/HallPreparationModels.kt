     * 값의 변경은 현재 패키지의 흐름과 후속 계산에 반영된다.
     */

    var attached = false
    /**
     * `zIndex` (상태 값): 객체가 유지하는 구성·진행 상태를 보관한다.
     * 값의 변경은 현재 패키지의 흐름과 후속 계산에 반영된다.
     */

    var zIndex = 0
