     * 값의 변경은 현재 패키지의 흐름과 후속 계산에 반영된다.
     */

    var pos = "10,20"
    /**
     * `tags` (상태 값): 객체가 유지하는 구성·진행 상태를 보관한다.
     * 값의 변경은 현재 패키지의 흐름과 후속 계산에 반영된다.
     */

    val tags = (0..4).toList()
    /**
     * `calls` (상태 값): 객체가 유지하는 구성·진행 상태를 보관한다.
     * 값의 변경은 현재 패키지의 흐름과 후속 계산에 반영된다.
     */

    val calls = mutableListOf<Int>()
    /**
     * `button`: 입력을 규칙에 따라 계산·변환한다.
     * 입력값을 현재 타입의 규칙에 따라 처리하고 결과 또는 상태 변화를 남긴다.
     */

    fun button(id: Int, event: Int) {
        if (event == 2 && id in 0..4) {
            attached = false; calls += id
        }
    }

    /**
     * `cancel`: 조건과 입력 상태를 검증한다.
     * 입력값을 현재 타입의 규칙에 따라 처리하고 결과 또는 상태 변화를 남긴다.
     */

    fun cancel(event: Int) {
        if (event == 2) attached = false
    }
}


/** BattleRosterModel: 전투 화면에 전달할 불변 표시 상태를 보관한다. */
class BattleRosterModel {
    /**
     * `slots` (상태 값): 객체가 유지하는 구성·진행 상태를 보관한다.
     * 값의 변경은 현재 패키지의 흐름과 후속 계산에 반영된다.
     */

    val slots = mutableListOf(-1, -1, -1)
    /**
     * `fights` (상태 값): 객체가 유지하는 구성·진행 상태를 보관한다.
     * 값의 변경은 현재 패키지의 흐름과 후속 계산에 반영된다.
     */

    val fights = linkedSetOf<Int>()
    /**
     * `label` (상태 값): 객체가 유지하는 구성·진행 상태를 보관한다.
     * 값의 변경은 현재 패키지의 흐름과 후속 계산에 반영된다.
     */

    var label = ""
    /**
     * `ok` (상태 값): 객체가 유지하는 구성·진행 상태를 보관한다.
     * 값의 변경은 현재 패키지의 흐름과 후속 계산에 반영된다.
     */

    var ok = true
    /**
     * `events` (상태 값): 객체가 유지하는 구성·진행 상태를 보관한다.
     * 값의 변경은 현재 패키지의 흐름과 후속 계산에 반영된다.
     */

    val events = mutableListOf<Int>()
    /**
     * `fight`: 타입의 핵심 동작을 수행한다.
     * 입력값을 현재 타입의 규칙에 따라 처리하고 결과 또는 상태 변화를 남긴다.
     */

    fun fight(id: Int) {
        val n = slots.indexOf(-1); if (n >= 0) {
            slots[n] = id; fights += id; ref()
        }
    }

    /**
     * `cancel`: 조건과 입력 상태를 검증한다.
     * 입력값을 현재 타입의 규칙에 따라 처리하고 결과 또는 상태 변화를 남긴다.
     */

    fun cancel(id: Int) {
        val n = slots.indexOf(id); if (n >= 0) {
            slots.removeAt(n); slots += -1; fights -= id; ref()
        }
    }

    /**
     * `ref`: 타입의 핵심 동작을 수행한다.
     * 입력값을 현재 타입의 규칙에 따라 처리하고 결과 또는 상태 변화를 남긴다.
     */

    private fun ref() {
        label = "출진 무장 - ${fights.size}/3"; ok = fights.size >= 2; events += fights.size
    }
}
